-- GRP: invitation, online queue and moderation.
CREATE TABLE invites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES groups(id),
    code CHAR(8) NOT NULL UNIQUE,
    created_by_member_id BIGINT NOT NULL REFERENCES group_members(id),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ
);
CREATE INDEX ix_invites_group_id ON invites (group_id);
CREATE TABLE online_queue (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    queued_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_online_queue_queued_at ON online_queue (queued_at);
CREATE TABLE blocks (
    blocker_member_id BIGINT NOT NULL REFERENCES group_members(id),
    blocked_member_id BIGINT NOT NULL REFERENCES group_members(id),
    created_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (blocker_member_id,blocked_member_id),
    CHECK (blocker_member_id <> blocked_member_id)
);
CREATE TABLE reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES groups(id),
    reporter_member_id BIGINT NOT NULL REFERENCES group_members(id),
    target_member_id BIGINT NOT NULL REFERENCES group_members(id),
    reason VARCHAR(12) NOT NULL CHECK(reason IN ('SPAM','HARASSMENT','OTHER')),
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (reporter_member_id,target_member_id)
);
CREATE INDEX ix_reports_target ON reports (group_id,target_member_id);
