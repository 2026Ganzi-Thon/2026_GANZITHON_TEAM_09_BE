-- #56에서 25곳 모두 전화·주소를 채웠으므로 같은 카드 안의 연락처와 어긋난다(프론트 테스트 보고 2026-11-20).
-- 연락처가 있는 센터만 바꾼다. 센터 행은 서비스 ID가 없어 공공서비스 동기화가 이 칸을 덮어쓰지 않는다.

UPDATE help_items
SET apply_method = '센터에 전화 또는 방문'
WHERE kind = 'LOCAL_CENTER'
  AND phone IS NOT NULL
  AND apply_method = '센터에 전화 또는 방문 (연락처는 센터 찾기에서 확인)';
