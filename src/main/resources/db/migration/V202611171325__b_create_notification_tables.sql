CREATE TABLE push_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    endpoint TEXT NOT NULL UNIQUE,
    p256dh VARCHAR(100) NOT NULL,
    auth VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_push_subscriptions_user ON push_subscriptions (user_id);

CREATE TABLE notification_settings (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    -- 30분 단위, null이면 미션 알림 끔
    mission_reminder_time TIME CHECK (EXTRACT(MINUTE FROM mission_reminder_time) IN (0, 30)
                                      AND EXTRACT(SECOND FROM mission_reminder_time) = 0),
    weekly_check_reminder BOOLEAN NOT NULL DEFAULT TRUE
);
