-- CHR-01~07: 그룹 캐릭터와 날짜별 확정 성장. erd.md 3절.
CREATE TABLE characters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES groups(id),
    kind VARCHAR(20) NOT NULL,
    started_on DATE NOT NULL,
    completed_on DATE,
    CHECK (completed_on IS NULL OR completed_on >= started_on)
);
-- 그룹마다 진행 중 캐릭터 1개(CHR-01)
CREATE UNIQUE INDEX uq_characters_group_active ON characters (group_id) WHERE completed_on IS NULL;
CREATE INDEX ix_characters_group ON characters (group_id);

-- 성장은 정수로만 저장하고 합은 그때그때 계산한다(CHR-04).
CREATE TABLE daily_group_progress (
    group_id BIGINT NOT NULL REFERENCES groups(id),
    date DATE NOT NULL,
    member_count SMALLINT NOT NULL CHECK (member_count BETWEEN 1 AND 6),
    completed_count SMALLINT NOT NULL CHECK (completed_count BETWEEN 0 AND member_count),
    finalized_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (group_id, date)
);
