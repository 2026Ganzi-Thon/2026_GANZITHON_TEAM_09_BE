-- GRP: group and membership history. Every user only has up to 3 ACTIVE memberships (app rule).
CREATE TABLE groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(10) NOT NULL CHECK (type IN ('FRIEND','ONLINE','SOLO')),
    name VARCHAR(12) NOT NULL,
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL,
    archived_at TIMESTAMPTZ
);
CREATE TABLE group_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES groups(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    display_name VARCHAR(20) NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL,
    left_at TIMESTAMPTZ,
    left_reason VARCHAR(20) CHECK (left_reason IN ('LEFT','INACTIVE','REPORTED','ACCOUNT_DELETED'))
);
CREATE UNIQUE INDEX uq_group_members_active_pair ON group_members (group_id,user_id) WHERE left_at IS NULL;
CREATE UNIQUE INDEX uq_group_members_active_display ON group_members (group_id,display_name) WHERE left_at IS NULL;
CREATE INDEX ix_group_members_user_active ON group_members (user_id) WHERE left_at IS NULL;
CREATE INDEX ix_group_members_historical ON group_members (group_id,joined_at,left_at);
